describe('reference overlay through installViaFileCopy (AC-2.4a)', () => {
  let claudeDir: string;
  let devflowDir: string;
  let warnings: string[];
  let manifest: readonly string[];

  const installedRefs = (): string => path.join(claudeDir, 'skills', 'devflow:git', 'references');

  async function runInstall() {
    return installViaFileCopy({
      plugins: [],
      claudeDir,
      devflowDir,
      skillsMap: new Map([['git', 'devflow-code-review']]),
      agentsMap: new Map(),
      isPartialInstall: false,
      spinner: noopSpinner,
      warn: (msg) => { warnings.push(msg); },
    });
  }

  beforeEach(async () => {
    manifest = await requireBuiltReferences();
    claudeDir = await fs.mkdtemp(path.join(os.tmpdir(), 'devflow-overlay-claude-'));
    devflowDir = await fs.mkdtemp(path.join(os.tmpdir(), 'devflow-overlay-home-'));
    warnings = [];
  });

  afterEach(async () => {
    await fs.rm(claudeDir, { recursive: true, force: true });
    await fs.rm(devflowDir, { recursive: true, force: true });
  });

  it('installs every canonical reference byte-equal to the generated source (canonical branch)', async () => {
    const report = await runInstall();

    for (const rel of manifest) {
      const installed = await fs.readFile(abs(installedRefs(), rel));
      const generated = await fs.readFile(abs(REAL_REFS, rel));
      expect(installed.equals(generated), `${rel} must be byte-equal to the generated source`).toBe(true);
    }
    expect([...report.overlaidRefs].sort()).toEqual([...manifest].sort());
    expect(report.overlayFailures).toEqual([]);
  });

  it('a SHADOWED devflow:git still receives the canonical GitHub references (AC-2.4a, UAC-28)', async () => {
    const shadow = path.join(devflowDir, 'skills', 'git');
    await fs.mkdir(shadow, { recursive: true });
    const sentinel = '# my own git skill\nSHADOW-SENTINEL-AC-2-4A\n';
    await fs.writeFile(path.join(shadow, 'SKILL.md'), sentinel, 'utf-8');

    const report = await runInstall();

    // The shadow is honoured …
    expect(report.shadowedSkills).toContain('git');
    expect(
      await fs.readFile(path.join(claudeDir, 'skills', 'devflow:git', 'SKILL.md'), 'utf-8'),
    ).toBe(sentinel);

    // … and the canonical mechanics still land. This is the release-blocker half.
    for (const rel of manifest.filter(p => p.startsWith('tracker/github/'))) {
      const installed = await fs.readFile(abs(installedRefs(), rel));
      const generated = await fs.readFile(abs(REAL_REFS, rel));
      expect(installed.equals(generated), `shadowed install must carry ${rel}`).toBe(true);
    }
    expect([...report.overlaidRefs].sort()).toEqual([...manifest].sort());
  });

  it('prunes a shadow-injected file under references/tracker/** (AC-2.4c)', async () => {
    const shadow = path.join(devflowDir, 'skills', 'git');
    await fs.mkdir(path.join(shadow, 'references', 'tracker', 'jira'), { recursive: true });
    await fs.writeFile(path.join(shadow, 'SKILL.md'), '# shadowed git\n', 'utf-8');
    const injected = path.join(shadow, 'references', 'tracker', 'jira', 'comment.md');
    await fs.writeFile(injected, '# injected mechanics\n', 'utf-8');

    const report = await runInstall();

    expect(
      await exists(path.join(installedRefs(), 'tracker', 'jira', 'comment.md')),
      'a shadow-supplied file that is not in the build manifest must be absent after install',
    ).toBe(false);
    expect(
      await exists(path.join(installedRefs(), 'tracker', 'jira')),
      'the orphaned provider directory must be removed, not left empty',
    ).toBe(false);

    // Positive half: the github set is complete and the prune is reported.
    for (const rel of manifest.filter(p => p.startsWith('tracker/github/'))) {
      expect(await exists(abs(installedRefs(), rel)), `${rel} must be present`).toBe(true);
    }
    expect(report.sweptOrphans.some(o => o.kind === 'reference')).toBe(true);
  });

  it('leaves hand-authored references from the skill source untouched', async () => {
    await runInstall();
    // github-api.md ships with the git skill and is not in the generated manifest.
    expect(await exists(path.join(installedRefs(), 'github-api.md'))).toBe(true);
    expect(generatedReferenceManifest()).not.toContain('github-api.md');
  });
});

