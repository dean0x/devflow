describe('atomic per-unit swap (AC-2.4b, DR-05, risk P2-g)', () => {
  let sourceRoot: string;
  let target: string;
  let manifest: readonly string[];
  let wide: string[];

  beforeEach(async () => {
    manifest = await requireBuiltReferences();
    wide = [...manifest, 'tracker/jira/comment.md', 'tracker/jira/transition.md'];
    sourceRoot = await fs.mkdtemp(path.join(os.tmpdir(), 'devflow-overlay-src-'));
    target = await fs.mkdtemp(path.join(os.tmpdir(), 'devflow-overlay-dst-'));
    await stageSource(sourceRoot, wide);
  });

  afterEach(async () => {
    await fs.chmod(abs(sourceRoot, 'tracker/jira/comment.md'), 0o644).catch(() => undefined);
    await fs.rm(sourceRoot, { recursive: true, force: true });
    await fs.rm(target, { recursive: true, force: true });
  });

  it('one unreadable file leaves that provider byte-unchanged and installs the others', async (ctx) => {
    const first = await overlayGeneratedReferences({ referencesTarget: target, sourceRoot, manifest: wide });
    expect(first.overlayFailures, 'the seeding install must succeed').toEqual([]);

    const jiraBefore = await Promise.all(
      ['tracker/jira/comment.md', 'tracker/jira/transition.md'].map(rel => fs.readFile(abs(target, rel))),
    );

    const revoked = await canRevokeRead(abs(sourceRoot, 'tracker/jira/comment.md'));
    if (!revoked) {
      // Running as root, or a filesystem that ignores mode bits: the premise of the
      // test cannot be established, so asserting on it would be theatre. Report it
      // as SKIPPED via vitest's ctx.skip() — a bare `return` here masked an
      // unestablished premise as a PASS, the PF-018 vacuous-green shape.
      ctx.skip();
      return;
    }

    // Mutate the github source so a no-op overlay is distinguishable from a real one.
    await fs.appendFile(abs(sourceRoot, 'tracker/github/setup-task.md'), '\n<!-- second pass -->\n');

    const second = await overlayGeneratedReferences({ referencesTarget: target, sourceRoot, manifest: wide });

    // 1. the failing unit is named, and the install still succeeds (no throw)
    expect(second.overlayFailures.map(f => f.provider)).toEqual(['jira']);
    expect(second.overlayFailures[0].error.length).toBeGreaterThan(0);

    // 2. the pre-existing provider tree is byte-unchanged — never a partial promotion
    const jiraAfter = await Promise.all(
      ['tracker/jira/comment.md', 'tracker/jira/transition.md'].map(rel => fs.readFile(abs(target, rel))),
    );
    expect(jiraAfter[0].equals(jiraBefore[0])).toBe(true);
    expect(jiraAfter[1].equals(jiraBefore[1])).toBe(true);

    // 3. the healthy unit installed normally (positive outcome)
    const installed = await fs.readFile(abs(target, 'tracker/github/setup-task.md'), 'utf-8');
    expect(installed).toContain('<!-- second pass -->');
    expect(second.overlaidRefs).toContain('tracker/github/setup-task.md');
    expect(second.overlaidRefs).not.toContain('tracker/jira/comment.md');

    // 4. no staging residue survives a failed unit
    const residue = (await walkTree(target)).filter(p => p.includes('.tmp'));
    expect(residue, 'a failed unit must leave no .tmp tree behind').toEqual([]);

    // 5. the failure reaches a render site (PF-015)
    const lines = formatOverlaySummary({
      overlaidRefs: second.overlaidRefs,
      overlayFailures: second.overlayFailures,
    });
    expect(lines.some(l => l.level === 'warn' && l.message.includes('jira'))).toBe(true);
  });

  it('a successful provider swap leaves no .old or .tmp residue behind', async () => {
    const result = await overlayGeneratedReferences({ referencesTarget: target, sourceRoot, manifest: wide });
    expect(result.overlayFailures, 'the swap must succeed for this assertion to mean anything').toEqual([]);

    // The promotion displaces the installed unit to a `.old` sibling before renaming
    // the staging tree over it, so the backup has to be dropped on the way out. A
    // surviving `.old` would be installed prose sitting beside the references the
    // agent reads, and — unlike `.tmp` — it holds a full previous copy.
    const residue = (await walkTree(target)).filter(p => p.includes('.old') || p.includes('.tmp'));
    expect(residue, 'a completed swap must leave neither backup nor staging residue').toEqual([]);
    // Positive outcome: the swap actually happened (avoids PF-018).
    expect(result.overlaidRefs).toContain('tracker/github/setup-task.md');
  });

  it('a promotion that fails after displacing the unit restores it instead of deleting it', async () => {
    const first = await overlayGeneratedReferences({ referencesTarget: target, sourceRoot, manifest: wide });
    expect(first.overlayFailures, 'the seeding install must succeed').toEqual([]);

    const unit: OverlayUnit = {
      id: 'jira',
      subdir: 'tracker/jira',
      files: ['tracker/jira/comment.md', 'tracker/jira/transition.md'],
    };
    const before = await Promise.all(unit.files.map(rel => fs.readFile(abs(target, rel))));

    // An ABSENT staging tree is the injectable stand-in for any rename that fails once
    // the installed unit has already been moved aside — the window a rm-then-rename
    // promotion cannot survive, because by then it has deleted the only copy. Driving
    // the real promotion step is what makes this a known-bad probe rather than a
    // restatement of the implementation (PF-018).
    const missingStaging = abs(target, 'tracker/jira') + '.tmp';
    expect(await exists(missingStaging), 'the staging tree must be absent for this probe').toBe(false);

    const promoted = await promoteUnitStagingTree(unit, target, missingStaging);

    expect(promoted.ok, 'promoting an absent staging tree must be reported, never silently ok').toBe(false);

    // The property: the previously installed mechanics are still there, byte for byte.
    // This is precisely what formatOverlaySummary's warning line tells the user, so it
    // is what has to be true.
    const after = await Promise.all(unit.files.map(rel => fs.readFile(abs(target, rel))));
    expect(
      after[0].equals(before[0]) && after[1].equals(before[1]),
      'a failed promotion must restore the displaced unit — leaving the provider empty ' +
      'would strip the agent of every mechanics file while the report claims nothing changed',
    ).toBe(true);

    // …and the backup it used is not left parked beside the live references.
    const residue = (await walkTree(target)).filter(p => p.includes('.old') || p.includes('.tmp'));
    expect(residue, 'a failed promotion must leave neither backup nor staging residue').toEqual([]);
  });

  it('an absent canonical GitHub reference fails loud with a build hint (AC-2.4b)', async () => {
    await fs.rm(abs(sourceRoot, 'tracker/github/setup-task.md'));

    await expect(
      overlayGeneratedReferences({ referencesTarget: target, sourceRoot, manifest: wide }),
    ).rejects.toThrow(/tracker\/github\/setup-task\.md/);
    await expect(
      overlayGeneratedReferences({ referencesTarget: target, sourceRoot, manifest: wide }),
    ).rejects.toThrow(/npm run build:mds/);
  });

  it('an absent cross-cutting document fails loud the same way', async () => {
    await fs.rm(abs(sourceRoot, 'decision-markers.md'));
    await expect(
      overlayGeneratedReferences({ referencesTarget: target, sourceRoot, manifest: wide }),
    ).rejects.toThrow(/decision-markers\.md[\s\S]*npm run build:mds/);
  });
});

