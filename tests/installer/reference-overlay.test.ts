describe('converge-not-merge staged swap (GAP-24)', () => {
  let sourceRoot: string;
  let target: string;
  let warnings: string[];
  let manifest: readonly string[];

  const EXTRA_PROVIDER_MANIFEST = ['tracker/jira/comment.md', 'tracker/jira/transition.md'] as const;

  beforeEach(async () => {
    manifest = await requireBuiltReferences();
    sourceRoot = await fs.mkdtemp(path.join(os.tmpdir(), 'devflow-overlay-src-'));
    target = await fs.mkdtemp(path.join(os.tmpdir(), 'devflow-overlay-dst-'));
    warnings = [];
  });

  afterEach(async () => {
    await fs.rm(sourceRoot, { recursive: true, force: true });
    await fs.rm(target, { recursive: true, force: true });
  });

  it('stale-reference prune: a provider directory the manifest no longer lists is removed', async () => {
    const wide = [...manifest, ...EXTRA_PROVIDER_MANIFEST];
    await stageSource(sourceRoot, wide);

    const first = await overlayGeneratedReferences({
      referencesTarget: target,
      sourceRoot,
      manifest: wide,
      warn: (m) => warnings.push(m),
    });
    expect(first.overlayFailures).toEqual([]);
    expect(
      await exists(path.join(target, 'tracker', 'jira', 'comment.md')),
      'the wide manifest must actually install the extra provider first',
    ).toBe(true);

    const second = await overlayGeneratedReferences({
      referencesTarget: target,
      sourceRoot,
      manifest,
      warn: (m) => warnings.push(m),
    });

    expect(await exists(path.join(target, 'tracker', 'jira'))).toBe(false);
    expect(
      second.pruned.scanned,
      'a prune that scanned nothing proves nothing (avoids PF-018)',
    ).toBeGreaterThan(0);
    expect(second.pruned.removed).toContain('jira');
    // Positive half: the retained set survived the prune.
    for (const rel of manifest.filter(p => p.startsWith('tracker/github/'))) {
      expect(await exists(abs(target, rel)), `${rel} must survive the prune`).toBe(true);
    }
  });

  it('skips a symlink entry in the source with a warning and never follows it', async () => {
    await stageSource(sourceRoot, manifest);
    const outside = path.join(sourceRoot, 'outside-the-tree');
    await fs.mkdir(outside, { recursive: true });
    await fs.writeFile(path.join(outside, 'smuggled.md'), '# smuggled\n', 'utf-8');
    await fs.symlink(outside, path.join(sourceRoot, 'tracker', 'github', 'linked'), 'dir');

    const result = await overlayGeneratedReferences({
      referencesTarget: target,
      sourceRoot,
      manifest,
      warn: (m) => warnings.push(m),
    });

    expect(result.overlayFailures).toEqual([]);
    expect([...result.overlaidRefs].sort()).toEqual([...manifest].sort());
    expect(warnings.some(w => w.includes('symlink'))).toBe(true);
    expect(await exists(path.join(target, 'tracker', 'github', 'linked'))).toBe(false);
    expect(await exists(path.join(target, 'tracker', 'github', 'smuggled.md'))).toBe(false);
  });

  it('normalises every installed reference to 0644', async () => {
    await stageSource(sourceRoot, manifest);
    await fs.chmod(abs(sourceRoot, 'tracker/github/setup-task.md'), 0o600);

    await overlayGeneratedReferences({ referencesTarget: target, sourceRoot, manifest });

    const files = (await walkTree(target)).filter(p => !p.endsWith('/'));
    expect(files.length, 'no files installed — the mode assertion would be vacuous').toBeGreaterThanOrEqual(13);
    for (const rel of files) {
      const stat = await fs.stat(abs(target, rel));
      expect(stat.mode & 0o777, `${rel} must be normalised to 0644`).toBe(0o644);
    }
  });
});

