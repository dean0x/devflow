/**
 * The files of {@link RETIRED_SHIPPED} as paths relative to the Claude dir: the command, agent and
 * rule files, and the listed files of a skill folder. A skill folder of `skills` is not a path
 * here, since the install moves it whole.
 */
export function retiredPathSet(): RetiredSet {
  const paths: string[] = [];
  for (const name of RETIRED_SHIPPED.commands) paths.push(`commands/devflow/${name}.md`);
  for (const name of RETIRED_SHIPPED.agents) paths.push(`agents/devflow/${name}.md`);
  for (const name of RETIRED_SHIPPED.rules) paths.push(`rules/devflow/${name}.md`);
  for (const [skill, files] of Object.entries(RETIRED_SHIPPED.skillFiles)) {
    for (const file of files) paths.push(`skills/${skill}/${file}`);
  }
  return createPathSet(paths);
}
